package com.campuscon.enums;

/**
 * Represents the type of a society deed
 */
public enum DeedType {
    EVENT,          // Physical/virtual event with a specific date and time
    ANNOUNCEMENT,   // General announcement without a specific event time
    RECRUITMENT,    // Recruitment or membership drive
    COMPETITION,    // Contest or competition
    WORKSHOP,       // Educational or skill-building workshop
    OTHER           // Other types of society deeds
}
